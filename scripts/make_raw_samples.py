from paths import RB, DATA, TEXTS  # set RB_ROOT, RB_DATA, RB_TEXTS to relocate
"""Gate G2 sheet: raw samples of merged incidents and QA / exclusion rates, for a human to read before trusting the aggregates.
Writes audit/raw_samples.md. Random samples use seed 2."""
import json, random, collections as C
RES = RB + 'results/'
att = [json.loads(l) for l in open(RES + 'attack_reports.jsonl')]
cl = json.load(open(RES + 'attack_clusters_main.json'))
grp = C.defaultdict(list)
for r in att: grp[cl[r['source_name']]].append(r)
multi = [g for g in grp.values() if len(g) > 1]
largest = sorted(multi, key=lambda g: -len(g))[:8]
random.seed(2); rnd = random.sample([g for g in multi if g not in largest], 8)
def show(g):
    out = []
    for r in sorted(g, key=lambda r: r['date'] or ''):
        out.append(f"  - {r['date'] or 'undated'} · {r['source_name']} · entities {', '.join(sorted(r['entities']))[:80]} · {len(r['techniques'])} techniques")
    return '\n'.join(out)
s = ["# Raw samples for gate G2 (generated by scripts/make_raw_samples.py)\n",
     "Read these before trusting the aggregates. For each incident, ask: are these reports about the same intrusion or campaign wave? "
     "Mark any that look wrong; the incidents are in results/attack_clusters_main.json and results/corpus_clusters_main.json.\n",
     "## QA and exclusion rates\n",
     f"- ATT&CK: {len(att):,} cited reports, {sum(1 for r in att if r['date']):,} dated ({sum(1 for r in att if r['date'])/len(att):.0%}); "
     f"{len(grp):,} incidents; {sum(len(g) for g in multi):,} reports in {len(multi):,} multi-report incidents; largest {max(len(g) for g in multi)} reports.",
]
ss = json.load(open(RES + 'attack_share_shift.json')); allt = C.Counter(t for r in att for t in set(r['techniques']))
s.append(f"- ATT&CK techniques: {len(allt)} seen, {len(ss)} tested (20+ report mentions); {len(allt) - len(ss)} excluded from the significance tests as too rare.")
cs = {x['setting']: x for x in json.load(open(RES + 'corpus_sensitivity.json'))}['ent+ioc_t60']
s.append(f"- Report texts: {cs['docs_all']:,} texts, {cs['labelled_docs']:,} with 3+ explicit technique IDs (the rest are used only for clustering and validation); "
         f"{cs['labelled_multi_report_incidents']} multi-report incidents among the labelled texts.")
tie = json.load(open(RES + 'tie_main_tech.json'))
s.append(f"- TIE: {tie['n_units_report']:,} entries, {tie['n_units_incident']:,} incidents; most entries are undated and cannot be linked (see paper, Sect. 3).")
p = json.load(open(RES + 'producer_vs_duplicate.json'))
s.append(f"- Producer: ATT&CK {p['attack']['n_vendors']} vendors, {p['attack']['n_unknown_producer']} reports without a URL; texts {p['corpus']['n_vendors']} vendors, {p['corpus']['n_unknown_producer']} texts without a URL.\n")
s.append("## ATT&CK: the 8 largest incidents\n")
for g in largest: s.append(f"**{len(g)} reports**\n{show(g)}\n")
s.append("## ATT&CK: 8 random multi-report incidents (seed 2)\n")
for g in rnd: s.append(f"**{len(g)} reports**\n{show(g)}\n")
s.append("## Report texts: every multi-report incident among the labelled texts\n")
s.append("```\n" + open(RES + 'corpus_multi_report_incidents.txt').read() + "```\n")
open(RB + 'audit/raw_samples.md', 'w').write('\n'.join(s))
print('wrote audit/raw_samples.md', len(largest), len(rnd))
